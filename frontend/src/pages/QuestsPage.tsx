import { Compass, Search } from 'lucide-react';
import { useMemo, useState } from 'react';
import { Button } from '../components/Button';
import { RadioChips } from '../components/ChoiceChips';
import { EmptyState } from '../components/EmptyState';
import { ErrorMessage } from '../components/ErrorMessage';
import { CardGridSkeleton, Skeleton } from '../components/LoadingState';
import { FitFinder } from '../components/quests/FitFinder';
import { QuestCard } from '../components/QuestCard';
import { SectionHeading } from '../components/SectionHeading';
import { QUEST_CATEGORY_IDS, QUEST_CATEGORY_META } from '../data/options';
import { useAsync } from '../hooks/useAsync';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import { api } from '../services/api';
import type { QuestCategory } from '../types';

type CategoryFilter = 'all' | QuestCategory;
type StatusFilter = 'all' | 'available' | 'in-progress' | 'completed';

const CATEGORY_OPTIONS: { value: CategoryFilter; label: string }[] = [
  { value: 'all', label: 'All quests' },
  ...QUEST_CATEGORY_IDS.map((id) => ({ value: id as CategoryFilter, label: QUEST_CATEGORY_META[id].label })),
];
const STATUS_OPTIONS: { value: StatusFilter; label: string }[] = [
  { value: 'all', label: 'Any status' },
  { value: 'available', label: 'Not started' },
  { value: 'in-progress', label: 'In progress' },
  { value: 'completed', label: 'Completed' },
];

export function QuestsPage() {
  useDocumentTitle('Outdoor quests', 'Small outdoor challenges in nature, movement, creativity, gardening, kindness and group activities, matched to your time, budget and energy.');
  const { data, error, loading, reload } = useAsync(() => api.getQuests(), []);
  const [category, setCategory] = useState<CategoryFilter>('all');
  const [status, setStatus] = useState<StatusFilter>('all');
  const [query, setQuery] = useState('');

  const visible = useMemo(() => {
    const q = query.trim().toLowerCase();
    return (data ?? []).filter(
      (quest) =>
        (category === 'all' || quest.category === category) &&
        (status === 'all' || quest.status === status) &&
        (!q || `${quest.title} ${quest.summary}`.toLowerCase().includes(q)),
    );
  }, [data, category, status, query]);
  const completedCount = data?.filter((quest) => quest.status === 'completed').length ?? 0;
  const filtered = category !== 'all' || status !== 'all' || query !== '';

  return (
    <div className="container-page py-12 lg:py-16">
      <SectionHeading
        as="h1"
        title="Outdoor quests"
        description="Short challenges you can finish in one outing. Start one, follow the steps, then log it to add it to your progress. Every quest is written by hand and curated, none are generated by a model."
      />

      <div className="mt-10">
        {loading && <Skeleton className="h-72 w-full rounded-3xl" />}
        {data && data.length > 0 && <FitFinder quests={data} />}
      </div>

      <h2 className="mt-16 text-3xl font-medium">All quests</h2>

      <div className="mt-6 space-y-4">
        <div className="max-w-md">
          <label htmlFor="quest-search" className="mb-2 block text-sm font-semibold text-forest-900">
            Search
          </label>
          <div className="relative">
            <Search className="pointer-events-none absolute left-3.5 top-1/2 h-4 w-4 -translate-y-1/2 text-forest-500" aria-hidden="true" />
            <input id="quest-search" type="search" className="input pl-10" value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Birds, sketch, picnic" />
          </div>
        </div>
        <div>
          <p id="quest-category-label" className="mb-2 text-sm font-semibold text-forest-900">
            Category
          </p>
          <RadioChips name="quest-category" options={CATEGORY_OPTIONS} value={category} onChange={setCategory} describedBy="quest-category-label" />
        </div>
        <div>
          <p id="quest-status-label" className="mb-2 text-sm font-semibold text-forest-900">
            Status
          </p>
          <RadioChips name="quest-status" options={STATUS_OPTIONS} value={status} onChange={setStatus} describedBy="quest-status-label" />
        </div>
      </div>

      <p className="mb-4 mt-8 text-sm text-forest-600" role="status" aria-live="polite">
        {data ? `${visible.length} quests shown, ${completedCount} of ${data.length} completed` : loading ? 'Loading quests' : ''}
      </p>

      {loading && <CardGridSkeleton count={6} label="Loading quests" />}
      {error && <ErrorMessage message={error} onRetry={reload} />}
      {data && visible.length === 0 && (
        <EmptyState
          icon={Compass}
          title="No quests match that combination"
          description="Try a different category, status or search to see more quests."
          action={
            <Button
              onClick={() => {
                setCategory('all');
                setStatus('all');
                setQuery('');
              }}
              disabled={!filtered}
            >
              Show all quests
            </Button>
          }
        />
      )}
      {data && visible.length > 0 && (
        <ul className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
          {visible.map((quest) => (
            <li key={quest.id}>
              <QuestCard quest={quest} />
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
