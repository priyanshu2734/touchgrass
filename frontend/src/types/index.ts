export type TimeOption = 10 | 20 | 30 | 60 | 120;
export type Budget = 'free' | 'low' | 'flexible';
export type Energy = 'low' | 'medium' | 'high';
export type Interest =
  | 'walking'
  | 'nature'
  | 'photography'
  | 'gardening'
  | 'fitness'
  | 'birdwatching'
  | 'creativity'
  | 'social';
export type Company = 'solo' | 'friends' | 'family' | 'group';
export type Difficulty = 'easy' | 'moderate' | 'challenging';
export type AccessibilityNeed =
  | 'step-free'
  | 'seating'
  | 'shade'
  | 'low-sensory'
  | 'short-distance';
export type QuestCategory =
  | 'nature-observation'
  | 'photography'
  | 'gardening'
  | 'walking'
  | 'kindness'
  | 'social';
/** "in-progress" is new in Part 3: the person tapped "Start quest" and has not finished it yet. */
export type QuestStatus = 'available' | 'in-progress' | 'completed';
/** How far you need to go to begin. Used by the barrier-aware matcher. */
export type TravelNeed = 'doorstep' | 'nearby' | 'short-trip';
export type DataSource = 'mock' | 'api';

export interface CostEstimate {
  min: number;
  max: number;
  /** ISO 4217 currency code, e.g. "USD". */
  currency: string;
}

/** Location is always optional and coarse. Coordinates are rounded to 2 decimals (~1 km). */
export interface LocationInput {
  label?: string;
  lat?: number;
  lon?: number;
}

export interface PlanPreferences {
  minutes: TimeOption;
  budget: Budget;
  energy: Energy;
  interests: Interest[];
  company: Company;
  accessibility: AccessibilityNeed[];
  notes?: string;
  location?: LocationInput;
}

export interface Activity {
  id: string;
  title: string;
  summary: string;
  type: string;
  minutes: number;
  cost: CostEstimate;
  budget: Budget;
  difficulty: Difficulty;
  energy: Energy;
  interests: Interest[];
  accessibility: AccessibilityNeed[];
  company: Company[];
  checklist: string[];
  tips: string[];
  /** Optional extras sent by the backend catalogue. */
  steps?: string[];
  challenge?: string;
}

export interface ChecklistItem {
  id: string;
  label: string;
}

export interface BackupOption {
  title: string;
  summary: string;
  durationMinutes: number;
  /** When to switch to the backup, if the planner said. */
  whenToUse?: string;
}

export interface PlanStep {
  order: number;
  title: string;
  description: string;
  durationMinutes: number;
}

/**
 * Where a plan came from. This is always shown to the person:
 *  - "ai"       the local open-weight model wrote it (and the backend validated it)
 *  - "fallback" the model was unavailable or its reply was unusable, so the backend built it from the built-in catalogue
 *  - "mock"     demo mode: simple rules in the browser, no backend at all
 */
export type PlanSource = 'mock' | 'ai' | 'fallback';

export interface ActivityPlan {
  id: string;
  title: string;
  summary: string;
  /** Short explanation of why this plan matched the preferences. */
  reason?: string;
  durationMinutes: number;
  estimatedCost: CostEstimate;
  checklist: ChecklistItem[];
  tips: string[];
  backup: BackupOption;
  accessibilityNotes?: string;
  generatedAt: string;
  source: PlanSource;
  model?: string;
  /** Part 2 additions (all optional so demo plans still fit). */
  steps?: PlanStep[];
  challenge?: string;
  accessibilityAdaptations?: string[];
  safetyReminders?: string[];
  phoneAwaySuggestion?: string;
  costAssumptions?: string;
  /** Why the fallback was used, in words for people. Present only when source is "fallback". */
  notice?: string;
  fallbackReason?: string;
}

export interface IndoorFallback {
  title: string;
  summary: string;
  minutes: number;
}

/**
 * Part 1 fields come first. Everything after `completedAt` is an additive Part 3 field and is optional,
 * so an older backend that does not send them still works (the UI simply hides what is missing).
 */
export interface Quest {
  id: string;
  title: string;
  summary: string;
  category: QuestCategory;
  difficulty: Difficulty;
  minutes: number;
  steps: string[];
  tip?: string;
  status: QuestStatus;
  completedAt?: string;
  objective?: string;
  equipment?: string[];
  completionCriteria?: string[];
  budget?: Budget;
  energy?: Energy;
  accessibility?: AccessibilityNeed[];
  company?: Company[];
  interests?: Interest[];
  travel?: TravelNeed;
  weatherSensitive?: boolean;
  indoorFallback?: IndoorFallback;
  /** Quests are a static, hand-written catalogue. They are never generated by a model. */
  origin?: 'curated';
  startedAt?: string;
  completionCount?: number;
}

export interface CompleteQuestInput {
  /** Minutes the person says they spent outdoors. Defaults to the quest's suggested time. */
  minutesSpent?: number;
  reflection?: string;
  /** Log another completion of an already-completed quest. */
  repeat?: boolean;
  /** The person's local calendar day (YYYY-MM-DD). Streaks are computed from this. */
  localDate?: string;
}

export interface SessionInput {
  minutes: number;
  note?: string;
  localDate?: string;
}

export interface Milestone {
  id: string;
  title: string;
  description: string;
  target: number;
  current: number;
  unit: 'quests' | 'days' | 'minutes';
  achieved: boolean;
}

export interface ProgressEntry {
  questId: string;
  title: string;
  completedAt: string;
  minutes: number;
  /** Part 3 additions (optional for older backends). */
  id?: string;
  kind?: 'quest' | 'session';
  note?: string;
  localDate?: string;
}

export interface Progress {
  completedActivities: number;
  outdoorMinutes: number;
  currentStreak: number;
  longestStreak: number;
  milestones: Milestone[];
  recent: ProgressEntry[];
  /** Part 3 additions (optional for older backends). */
  activeDays?: number;
  sessionsLogged?: number;
  /** Local dates (YYYY-MM-DD) with at least one entry in the last 28 days. */
  activeDates?: string[];
  /** Plans this anonymous profile has generated (kept by the backend as a count only). */
  plansGenerated?: number;
}

export interface CompleteQuestResponse {
  quest: Quest;
  progress: Progress;
}

export interface Place {
  id: string;
  name: string;
  category: string;
  lat: number;
  lon: number;
  distanceMeters?: number;
  /** Part 3 additions. All come straight from OpenStreetMap tags and are never filled in by us. */
  categoryId?: string;
  osmUrl?: string;
  /** Raw OSM `opening_hours` value. Unverified and possibly out of date. */
  openingHours?: string;
  /** Raw OSM `wheelchair` value. Unverified. */
  wheelchair?: 'yes' | 'limited' | 'no';
  website?: string;
  /** False when OpenStreetMap has no name for this feature. */
  named?: boolean;
}

export interface PlaceCategory {
  id: string;
  label: string;
  defaultOn: boolean;
}

export interface GeocodeResult {
  label: string;
  lat: number;
  lon: number;
}

export type BarrierId =
  | 'short-time'
  | 'no-budget'
  | 'low-energy'
  | 'solo'
  | 'accessible'
  | 'near-home'
  | 'bad-weather'
  | 'quiet';

export type AiStatus = 'ready' | 'model_missing' | 'unreachable' | 'disabled';

export interface HealthStatus {
  /** ok = everything ready, degraded = AI not ready but fallback plans work, error = database down. */
  status: 'ok' | 'degraded' | 'error';
  /** "mock" in demo mode. */
  mode?: string;
  ai?: {
    status: AiStatus;
    model: string;
    /** What to do next when the AI is not ready, e.g. the `ollama pull` command. */
    setupHint?: string;
  };
}
