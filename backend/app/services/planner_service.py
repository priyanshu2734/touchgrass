"""Chooses AI or fallback and records privacy-safe history. Never claims AI when it was not used."""

from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4

from app.models.domain import PlanHistoryRecord, PlanInput
from app.repositories.history import HistoryRepository
from app.services.ai_errors import AIError
from app.services.ai_service import AIService
from app.services.catalog_service import CatalogService
from app.services.fallback_planner import build_fallback_plan
from app.services.matching import rank_activities

logger = logging.getLogger(__name__)

FALLBACK_NOTICE = (
    "This plan was built from TouchGrass's built-in activity catalogue and rules. "
    "It was not generated by an AI model."
)


@dataclass(frozen=True)
class PlanResult:
    plan: dict[str, Any]  # includes id, generated_by, model, generated_at
    generated_by: str  # "ai" | "fallback"
    model: str | None
    fallback_reason: str | None
    message: str | None


class PlannerService:
    def __init__(self, ai: AIService, catalog: CatalogService, history: HistoryRepository) -> None:
        self._ai = ai
        self._catalog = catalog
        self._history = history

    async def create_plan(self, inp: PlanInput, profile_id: str) -> PlanResult:
        ranked = rank_activities(inp, self._catalog.all_activities())
        reason: str | None = None
        message: str | None = None
        plan_body: dict[str, Any] | None = None
        model: str | None = None

        try:
            result = await self._ai.generate_plan(inp, ranked[:3])
            plan_body, model = result.plan, result.model
        except AIError as exc:
            reason = exc.code
            message = f"{exc.public_message} {FALLBACK_NOTICE}"
            logger.warning("AI plan unavailable (%s): %s", exc.code, exc.detail)
        except Exception:  # defensive: any provider bug must not break the endpoint
            reason = "ai_error"
            message = f"The AI service had an unexpected problem. {FALLBACK_NOTICE}"
            logger.exception("Unexpected error while generating an AI plan")

        generated_by = "ai" if plan_body is not None else "fallback"
        if plan_body is None:
            plan_body = build_fallback_plan(inp, ranked)

        plan = {
            "id": f"plan-{uuid4().hex[:12]}",
            "generated_by": generated_by,
            "model": model,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            **plan_body,
        }

        await self._record(profile_id, plan, inp)
        return PlanResult(plan=plan, generated_by=generated_by, model=model, fallback_reason=reason, message=message)

    async def _record(self, profile_id: str, plan: dict[str, Any], inp: PlanInput) -> None:
        record = PlanHistoryRecord(
            plan_id=plan["id"],
            profile_id=profile_id,
            created_at=plan["generated_at"],
            generated_by=plan["generated_by"],
            model=plan["model"],
            title=plan["title"],
            total_minutes=plan["total_minutes"],
            budget=inp.budget,
            energy=inp.energy,
            interests=inp.interests,
        )
        try:
            await asyncio.to_thread(self._history.add, record)
        except Exception:  # history is best effort and must never fail the request
            logger.exception("Could not save plan history")
