def test_coordinates_and_history_privacy(make_client):
    provider = FakeProvider()
    client = make_client(provider=provider)
    body = {**PLAN_BODY, "notes": "prefer quiet", "location": {"label": "Riverside", "lat": 12.9716, "lon": 77.5946}}
    assert client.post("/api/plan", json=body, headers={"X-Profile-Id": "profile-privacy-1"}).status_code == 200
    user_prompt = provider.calls[0]["user"]
    assert "Riverside" in user_prompt and "prefer quiet" in user_prompt
    assert "12.97" not in user_prompt and "77.59" not in user_prompt and "lat" not in user_prompt.lower()

    history = client.get("/api/history", headers={"X-Profile-Id": "profile-privacy-1"}).json()
    assert history["count"] == 1 and history["items"][0]["generated_by"] == "ai"
    assert "Riverside" not in str(history) and "prefer quiet" not in str(history)
    assert client.get("/api/history", headers={"X-Profile-Id": "profile-other-22"}).json()["count"] == 0


