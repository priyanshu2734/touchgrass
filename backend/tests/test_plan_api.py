import pytest

from app.services.ai_errors import AIModelMissingError, AIServerError, AITimeoutError, AIUnavailableError
from tests.conftest import PLAN_BODY
from tests.helpers import FakeProvider, valid_ai_payload


def test_valid_request_returns_validated_ai_plan(client):
    res = client.post("/api/plan", json=PLAN_BODY)
    assert res.status_code == 200
    body = res.json()
    assert body["generated_by"] == "ai" and body["model"] == "fake-model:1b"
    assert body["fallback_reason"] is None and body["message"] is None
    plan = body["plan"]
    assert plan["generated_by"] == "ai"
    assert plan["total_minutes"] <= PLAN_BODY["available_minutes"]
    assert [s["order"] for s in plan["steps"]] == list(range(1, len(plan["steps"]) + 1))
    for key in ("estimated_cost", "checklist", "backup_plan", "safety_reminders", "phone_away_suggestion", "why_it_matches"):
        assert plan[key]


