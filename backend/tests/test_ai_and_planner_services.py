def run(coro):
    return asyncio.run(coro)


def planner(tmp_path, provider, enabled=True):
    db = Database(str(tmp_path / "t.db"))
    db.init_schema()
    return PlannerService(AIService(provider, enabled=enabled), CatalogService(), HistoryRepository(db)), db


# --- AIService ---------------------------------------------------------------

def test_ai_service_returns_normalised_plan_and_model_name():
    provider = FakeProvider()
    inp = make_input()
    result = run(AIService(provider).generate_plan(inp, rank_activities(inp, ACTIVITIES)[:3]))
    assert result.model == "fake-model:1b"
    assert result.plan["total_minutes"] == 45
    call = provider.calls[0]
    assert "JSON" in call["system"] and call["schema"]["type"] == "object"


def test_prompt_contains_preferences_but_no_coordinates():
    provider = FakeProvider()
    inp = make_input(area="Riverside", notes="I use a cane")
    run(AIService(provider).generate_plan(inp, []))
    user = provider.calls[0]["user"]
    assert "Riverside" in user and "I use a cane" in user
    assert "lat" not in user.lower() and "lon" not in user.lower()


def test_status_values():
    assert run(AIService(FakeProvider()).status()).status == "ready"
    missing = FakeProvider(status=ProviderStatus(True, False, ("other:1b",)))
    s = run(AIService(missing).status())
    assert s.status == "model_missing" and "ollama pull fake-model:1b" in s.setup_hint
    down = FakeProvider(status=ProviderStatus(False, False))
    assert run(AIService(down).status()).status == "unreachable"
    assert run(AIService(FakeProvider(), enabled=False).status()).status == "disabled"
    assert run(AIService(None).status()).status == "disabled"


# --- PlannerService: AI success and every failure path -----------------------

def test_ai_plan_is_labelled_ai(tmp_path):
    svc, _ = planner(tmp_path, FakeProvider())
    result = run(svc.create_plan(make_input(), "p1"))
    assert result.generated_by == "ai" and result.model == "fake-model:1b"
    assert result.fallback_reason is None and result.message is None
    assert result.plan["generated_by"] == "ai" and result.plan["id"].startswith("plan-")


def test_every_failure_falls_back_and_is_never_called_ai(tmp_path):
    cases = [
        (FakeProvider(error=AITimeoutError("t")), "ai_timeout"),
        (FakeProvider(error=AIUnavailableError("u")), "ai_unreachable"),
        (FakeProvider(error=AIModelMissingError("m")), "ai_model_missing"),
        (FakeProvider(error=AIServerError("s")), "ai_server_error"),
        (FakeProvider(error=RuntimeError("boom with /secret/path")), "ai_error"),
        (FakeProvider(reply="this is not json"), "ai_invalid_response"),
        (FakeProvider(reply=valid_ai_payload(steps=[])), "ai_invalid_response"),
        (FakeProvider(reply=valid_ai_payload(energy_required="high")), "ai_invalid_response"),
    ]
    for provider, code in cases:
        svc, _ = planner(tmp_path, provider)
        result = run(svc.create_plan(make_input(energy="low"), "p"))
        assert result.generated_by == "fallback", code
        assert result.model is None and result.fallback_reason == code
        assert "not generated by an AI model" in result.message
        assert "/secret/path" not in result.message and "boom" not in result.message
        assert result.plan["generated_by"] == "fallback" and result.plan["model"] is None


def test_disabled_ai_uses_fallback(tmp_path):
    svc, _ = planner(tmp_path, FakeProvider(), enabled=False)
    result = run(svc.create_plan(make_input(), "p"))
    assert result.generated_by == "fallback" and result.fallback_reason == "ai_disabled"


def test_history_is_recorded_without_location_or_notes(tmp_path):
    svc, db = planner(tmp_path, FakeProvider())
    run(svc.create_plan(make_input(area="Secret Town", notes="private note"), "p1"))
    with db.connect() as conn:
        dump = json.dumps([dict(r) for r in conn.execute("SELECT * FROM plan_history")])
    assert "Secret Town" not in dump and "private note" not in dump
    assert HistoryRepository(db).count("p1") == 1
